/* --------------------------------------------------
   ORBIT Saved Storage
   Device-local persistence for saved NASA images
-------------------------------------------------- */

/*
  Storage schema version.

  If ORBIT's saved-record structure changes
  significantly in the future, a new version can use
  a new key without confusing older stored data.
*/

const STORAGE_KEY = "orbit:saved:v1";

/* --------------------------------------------------
   Basic value helpers
-------------------------------------------------- */

function cleanString(value) {
  return typeof value === "string" ? value.trim() : "";
}

function normaliseId(value) {
  return cleanString(value).toLowerCase();
}

function normaliseKeywords(value) {
  if (!Array.isArray(value)) {
    return [];
  }

  const uniqueKeywords = new Set();

  for (const keyword of value) {
    const cleaned = cleanString(keyword);

    if (cleaned) {
      uniqueKeywords.add(cleaned);
    }
  }

  return [...uniqueKeywords];
}

function getTimestamp(value) {
  const cleaned = cleanString(value);

  if (!cleaned) {
    return 0;
  }

  const timestamp = Date.parse(cleaned);

  return Number.isFinite(timestamp) ? timestamp : 0;
}

/* --------------------------------------------------
   Saved-record normalisation
-------------------------------------------------- */

/*
  Used when reading records that already exist in
  localStorage.

  Required:
  - nasaId
  - title

  Optional values are safely defaulted.
*/

function normaliseStoredItem(item) {
  if (!item || typeof item !== "object" || Array.isArray(item)) {
    return null;
  }

  const nasaId = cleanString(item.nasaId ?? item.nasa_id);

  const title = cleanString(item.title);

  if (!nasaId || !title) {
    return null;
  }

  return {
    nasaId,

    title,

    imageUrl: cleanString(item.imageUrl),

    center: cleanString(item.center) || "NASA",

    dateCreated: cleanString(
      item.dateCreated ?? item.date_created ?? item.date,
    ),

    description: cleanString(
      item.description ?? item.description508 ?? item.description_508,
    ),

    keywords: normaliseKeywords(item.keywords),

    savedAt: cleanString(item.savedAt),
  };
}

/*
  Used when saving a new NASA record.

  savedAt is always generated by ORBIT instead of
  trusting a timestamp supplied by page code.
*/

function createSavedRecord(item) {
  const stored = normaliseStoredItem(item);

  if (!stored) {
    return null;
  }

  return {
    ...stored,

    savedAt: new Date().toISOString(),
  };
}

/* --------------------------------------------------
   Ordering
-------------------------------------------------- */

function sortNewestFirst(items) {
  return [...items].sort((first, second) => {
    return getTimestamp(second.savedAt) - getTimestamp(first.savedAt);
  });
}

/* --------------------------------------------------
   Duplicate cleanup
-------------------------------------------------- */

/*
  nasaId is ORBIT's authoritative Saved identity.

  Stored IDs preserve their original case, but
  duplicate comparison is case-insensitive.
*/

function deduplicateSavedItems(items) {
  const sorted = sortNewestFirst(items);

  const seenIds = new Set();

  const unique = [];

  for (const item of sorted) {
    const id = normaliseId(item.nasaId);

    if (!id || seenIds.has(id)) {
      continue;
    }

    seenIds.add(id);

    unique.push(item);
  }

  return unique;
}

/* --------------------------------------------------
   localStorage access
-------------------------------------------------- */

function getLocalStorage() {
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

/*
  Internal read function.

  Important distinction:

  - inaccessible localStorage:
      ok = false

  - malformed JSON:
      ok = true
      items = []

  Corrupt JSON is treated as an empty Saved
  collection so ORBIT remains usable and the next
  successful Save can repair the stored collection.

  A true browser/storage access failure is different:
  mutation functions must not pretend they succeeded.
*/

function readStorage() {
  const storage = getLocalStorage();

  if (!storage) {
    return {
      ok: false,
      items: [],
    };
  }

  let rawValue = null;

  try {
    rawValue = storage.getItem(STORAGE_KEY);
  } catch {
    return {
      ok: false,
      items: [],
    };
  }

  if (!rawValue) {
    return {
      ok: true,
      items: [],
    };
  }

  let parsedValue;

  try {
    parsedValue = JSON.parse(rawValue);
  } catch {
    return {
      ok: true,
      items: [],
    };
  }

  if (!Array.isArray(parsedValue)) {
    return {
      ok: true,
      items: [],
    };
  }

  const validItems = parsedValue.map(normaliseStoredItem).filter(Boolean);

  return {
    ok: true,

    items: deduplicateSavedItems(validItems),
  };
}

/*
  Internal write function.

  Returns false instead of throwing if storage is
  unavailable, blocked, or full.
*/

function writeStorage(items) {
  const storage = getLocalStorage();

  if (!storage) {
    return false;
  }

  const safeItems = deduplicateSavedItems(
    items.map(normaliseStoredItem).filter(Boolean),
  );

  try {
    storage.setItem(STORAGE_KEY, JSON.stringify(safeItems));

    return true;
  } catch {
    return false;
  }
}

/* --------------------------------------------------
   Public API
-------------------------------------------------- */

/*
  getSavedItems()

  Always returns an array.

  If Saved storage cannot be read, ORBIT safely
  behaves as though the collection is empty instead
  of crashing the page.
*/

export function getSavedItems() {
  const result = readStorage();

  return result.items;
}

/*
  isItemSaved(nasaId)

  nasaId comparison is case-insensitive and ignores
  accidental surrounding whitespace.
*/

export function isItemSaved(nasaId) {
  const targetId = normaliseId(nasaId);

  if (!targetId) {
    return false;
  }

  return getSavedItems().some((item) => {
    return normaliseId(item.nasaId) === targetId;
  });
}

/*
  saveItem(item)

  Success:
  {
    ok: true,
    saved: true,
    added: true | false,
    item: savedRecord
  }

  Duplicate Saves are idempotent:
  saving the same NASA ID repeatedly never creates
  multiple stored records.

  Failure:
  {
    ok: false,
    saved: false,
    added: false,
    item: null,
    reason: "..."
  }
*/

export function saveItem(item) {
  const record = createSavedRecord(item);

  if (!record) {
    return {
      ok: false,
      saved: false,
      added: false,
      item: null,
      reason: "invalid-item",
    };
  }

  const stored = readStorage();

  /*
    Do not overwrite unknown existing data if the
    browser has blocked localStorage access.
  */

  if (!stored.ok) {
    return {
      ok: false,
      saved: false,
      added: false,
      item: null,
      reason: "storage-unavailable",
    };
  }

  const targetId = normaliseId(record.nasaId);

  const existing = stored.items.find((savedItem) => {
    return normaliseId(savedItem.nasaId) === targetId;
  });

  /*
    Idempotent Save:
    the item is already safely stored, so no write is
    required and its original savedAt is preserved.
  */

  if (existing) {
    return {
      ok: true,
      saved: true,
      added: false,
      item: existing,
    };
  }

  const nextItems = [record, ...stored.items];

  const written = writeStorage(nextItems);

  if (!written) {
    return {
      ok: false,
      saved: false,
      added: false,
      item: null,
      reason: "storage-write-failed",
    };
  }

  return {
    ok: true,
    saved: true,
    added: true,
    item: record,
  };
}

/*
  removeSavedItem(nasaId)

  Removing something that is already absent is safe.

  Success when removed:
  {
    ok: true,
    removed: true,
    item: removedRecord
  }

  Success when already absent:
  {
    ok: true,
    removed: false,
    item: null
  }
*/

export function removeSavedItem(nasaId) {
  const targetId = normaliseId(nasaId);

  if (!targetId) {
    return {
      ok: false,
      removed: false,
      item: null,
      reason: "invalid-id",
    };
  }

  const stored = readStorage();

  if (!stored.ok) {
    return {
      ok: false,
      removed: false,
      item: null,
      reason: "storage-unavailable",
    };
  }

  const existing = stored.items.find((item) => {
    return normaliseId(item.nasaId) === targetId;
  });

  /*
    Already absent is not an error.
  */

  if (!existing) {
    return {
      ok: true,
      removed: false,
      item: null,
    };
  }

  const nextItems = stored.items.filter((item) => {
    return normaliseId(item.nasaId) !== targetId;
  });

  const written = writeStorage(nextItems);

  if (!written) {
    return {
      ok: false,
      removed: false,
      item: null,
      reason: "storage-write-failed",
    };
  }

  return {
    ok: true,
    removed: true,
    item: existing,
  };
}

/*
  toggleSavedItem(item)

  If already saved:
      removes it

  If not saved:
      saves it

  The returned "saved" value represents the state
  after the operation.
*/

export function toggleSavedItem(item) {
  const nasaId = cleanString(item?.nasaId ?? item?.nasa_id);

  if (!nasaId) {
    return {
      ok: false,
      saved: false,
      item: null,
      reason: "invalid-item",
    };
  }

  if (isItemSaved(nasaId)) {
    const removal = removeSavedItem(nasaId);

    if (!removal.ok) {
      /*
        Removal failed, therefore the existing item
        should still be considered saved.
      */

      return {
        ok: false,
        saved: true,
        item: removal.item,
        reason: removal.reason ?? "storage-write-failed",
      };
    }

    return {
      ok: true,
      saved: false,
      item: null,
    };
  }

  const saved = saveItem(item);

  return {
    ok: saved.ok,
    saved: saved.saved,
    item: saved.item,
    ...(saved.reason
      ? {
          reason: saved.reason,
        }
      : {}),
  };
}
